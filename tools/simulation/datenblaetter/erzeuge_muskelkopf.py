"""Schreibt sources/simulation/simulationmuscle.h aus dmsp.json (Festo-Katalog DMSP 2026/01, S. 12–15).

Aufruf: python -I erzeuge_muskelkopf.py dmsp.json ziel.h
"""
import json
import sys

D = json.load(open(sys.argv[1], encoding="utf-8"))
# Typ: (I.D. [m], Gewicht bei 0 m Länge DMSP-...-RM-CM [kg], Zusatzgewicht je m [kg/m], max. Vorspannung [%],
#       max. Kontraktion [%], max. Betriebsdruck [bar], theoretische Kraft [N], Aufweitung bei max. Kontraktion [m])
DATEN = {
    "DMSP-10": (0.010, 0.058, 0.094, 3.0, 25.0, 8.0, 630.0, 0.024),
    "DMSP-20": (0.020, 0.169, 0.178, 4.0, 25.0, 6.0, 1500.0, 0.040),
    "DMSP-40": (0.040, 0.675, 0.340, 5.0, 25.0, 6.0, 6000.0, 0.080),
}

z = ["// Generated by erzeuge_muskelkopf.py from the Festo catalogue \"Fluidic Muscle DMSP\" (DMSP_EN.PDF, 2026/01):",
     "// force/displacement graphs p. 14/15 read exactly from the vector paths (axis ticks fitted, residual < 0.07 %",
     "// contraction / 0.3 N), technical data p. 12/13. Do not edit by hand (FORMELN.md M15).",
     "#ifndef SIMULATIONMUSCLE_H", "#define SIMULATIONMUSCLE_H", "", "#include <algorithm>", "#include <cmath>",
     "#include <vector>", "", "namespace SimMuscle {", "",
     "struct Point { double h, f; };   ///< contraction [% of the nominal length], force [N]", "",
     "struct Type {",
     "\tconst char *name;",
     "\tdouble id;            ///< inner diameter [m]",
     "\tdouble m0, m_per_m;   ///< product weight at 0 m length [kg], additional weight per metre [kg/m]",
     "\tdouble pre, h_max;    ///< max. pretension, max. contraction [% of the nominal length]",
     "\tdouble p_max;         ///< max. operating pressure [bar]",
     "\tdouble f_theo;        ///< theoretical force at max. operating pressure [N]",
     "\tdouble d_max;         ///< diameter expansion at max. contraction [m]",
     "\tstd::vector<std::vector<Point>> curves;   ///< index = pressure in bar (0, 1, 2 …)",
     "};", "",
     "inline const std::vector<Type> &types()", "{", "\tstatic const std::vector<Type> t = {"]
for typ, (idm, m0, mm, pre, hmax, pmax, ft, dmax) in DATEN.items():
    z.append(f'\t\t{{"{typ}", {idm}, {m0}, {mm}, {pre}, {hmax}, {pmax}, {ft}, {dmax}, {{')
    for bar, pts in sorted(D[typ]["kurven_bar"].items(), key=lambda kv: int(kv[0])):
        werte = ", ".join(f"{{{h:g}, {f:g}}}" for h, f in pts)
        z.append(f"\t\t\t{{{werte}}},   // {bar} bar")
    z.append("\t\t}},")
z += ["\t};", "\treturn t;", "}", "",
      "/// a curve at the contraction h; outside its ends continued linearly with the end segment",
      "inline double curveAt(const std::vector<Point> &c, double h)",
      "{",
      "\tstd::size_t i = 1;",
      "\tif (h >= c.back().h) i = c.size() - 1;",
      "\telse if (h > c.front().h)",
      "\t\twhile (i + 1 < c.size() && c[i].h < h) ++i;",
      "\tconst Point &a = c[i - 1], &b = c[i];",
      "\treturn b.h != a.h ? a.f + (b.f - a.f) * (h - a.h) / (b.h - a.h) : a.f;",
      "}", "",
      "/// tensile force [N] at the contraction h [%] and the gauge pressure bar: linear between the curves of",
      "/// neighbouring pressures, above the highest curve continued linearly, below 0 bar the 0-bar curve",
      "inline double force(const Type &t, double h, double bar)",
      "{",
      "\tconst int n = static_cast<int>(t.curves.size()) - 1;",
      "\tconst double b = std::max(bar, 0.0);",
      "\tconst int i = std::min(static_cast<int>(std::floor(b)), n - 1);",
      "\tconst double f0 = curveAt(t.curves[i], h), f1 = curveAt(t.curves[i + 1], h);",
      "\treturn f0 + (f1 - f0) * (b - i);",
      "}", "",
      "/// effective area dF/dp [m²] at the contraction h: least squares slope over all pressure curves",
      "inline double area(const Type &t, double h)",
      "{",
      "\tconst int n = static_cast<int>(t.curves.size());",
      "\tdouble mp = 0, mf = 0;",
      "\tstd::vector<double> f(n);",
      "\tfor (int i = 0; i < n; ++i) { f[i] = curveAt(t.curves[i], h); mp += i; mf += f[i]; }",
      "\tmp /= n; mf /= n;",
      "\tdouble sxy = 0, sxx = 0;",
      "\tfor (int i = 0; i < n; ++i) { sxy += (i - mp) * (f[i] - mf); sxx += (i - mp) * (i - mp); }",
      "\treturn sxy / sxx / 1e5;",
      "}", "",
      "/// volume per metre nominal length [m³/m] at the contraction h by virtual work: V = π/4·I.D.² + ∫₀^h A dh",
      "inline double volumePerMetre(const Type &t, double h)",
      "{",
      "\tconst int n = std::max(1, static_cast<int>(std::ceil(std::abs(h) / 0.05)));",
      "\tdouble v = M_PI / 4 * t.id * t.id, a0 = area(t, 0.0);",
      "\tfor (int i = 1; i <= n; ++i) {",
      "\t\tconst double a1 = area(t, h * i / n);",
      "\t\tv += 0.5 * (a0 + a1) * (h / n) / 100.0;",
      "\t\ta0 = a1;",
      "\t}",
      "\treturn v;",
      "}", "",
      "}   // namespace SimMuscle", "", "#endif // SIMULATIONMUSCLE_H", ""]
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(z))
print(sum(len(c) for v in D.values() for c in v["kurven_bar"].values()), "Punkte")
